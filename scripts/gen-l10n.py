#!/usr/bin/env python3
"""Embeds localization/strings.json into Swift as a dictionary literal (English key → language → text),
so the app needs no resource bundle. Run after editing translations: python3 scripts/gen-l10n.py"""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "localization/strings.json").read_text())


def lit(s: str) -> str:
    """A Swift string literal: escapes backslash, quote and control characters (\\u{XX})."""
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        elif ch == "\r": out.append("\\r")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F: out.append("\\u{%X}" % ord(ch))
        else: out.append(ch)
    return '"' + "".join(out) + '"'


# One dictionary literal per small chunk: a single huge literal makes `swift build -c release`
# take minutes in the optimizer, while small literals compile in seconds.
CHUNK = 16
keys = sorted(data)
chunks = [keys[i:i + CHUNK] for i in range(0, len(keys), CHUNK)]
lines = [
    "// GENERATED by scripts/gen-l10n.py from localization/strings.json. Do not edit.",
    f"// {len(data)} keys.",
    "",
    "enum L10nData {",
    "    /// English key → language code → text.",
    "    static let table: [String: [String: String]] = {",
    "        var table: [String: [String: String]] = [:]",
]
for i in range(len(chunks)):
    lines.append(f"        table.merge(chunk{i}()) {{ a, _ in a }}")
lines += ["        return table", "    }()"]
for i, chunk in enumerate(chunks):
    lines += ["", "    @inline(never)", f"    private static func chunk{i}() -> [String: [String: String]] {{", "        ["]
    for key in chunk:
        lines.append(f"            {lit(key)}: [")
        for lang in sorted(data[key]):
            lines.append(f"                {lit(lang)}: {lit(data[key][lang])},")
        lines.append("            ],")
    lines += ["        ]", "    }"]
lines += ["}", ""]

out = root / "Sources/FreeroomApp/L10nData.swift"
out.write_text("\n".join(lines))
print(f"Wrote {out.relative_to(root)} ({len(data)} keys)")
