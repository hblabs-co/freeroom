#!/usr/bin/env python3
"""Embeds catalog/catalog.json into Swift so the app, the CLI and the tests share one copy
without resource bundles. Run after editing the catalog: python3 scripts/gen-catalog.py"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / "catalog/catalog.json").read_text())
compact = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
assert '"##' not in compact
# Translations: catalog/i18n/<lang>.json = {id: {title, explanation}}. Missing entries fall back to English.
ids = {e["id"] for e in data}
translations = {}
for path in sorted((root / "catalog/i18n").glob("*.json")):
    table = json.loads(path.read_text())
    missing = ids - table.keys()
    if missing:
        print(f"warning: {path.name} is missing {len(missing)} entries (English will be shown): {sorted(missing)[:5]}")
    translations[path.stem] = {k: v for k, v in table.items() if k in ids}
i18n = json.dumps(translations, ensure_ascii=False, separators=(",", ":"))
assert '"##' not in i18n

out = root / "Sources/FreeroomCore/Locations/CatalogData.swift"
out.write_text(
    "// GENERATED by scripts/gen-catalog.py from catalog/catalog.json and catalog/i18n/*.json. Do not edit.\n"
    f"// {len(data)} entries, {len(translations)} translations.\n\n"
    "enum CatalogData {\n"
    f"    static let json = ##\"{compact}\"##\n\n"
    f"    static let i18n = ##\"{i18n}\"##\n"
    "}\n"
)
print(f"Wrote {out.relative_to(root)} ({len(data)} entries, languages: {', '.join(translations)})")
